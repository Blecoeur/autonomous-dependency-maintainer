import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { RepairRequest } from '../types.js';

/**
 * The vibe configuration the repair run uses ($VIBE_HOME/config.toml).
 *
 * Written into an isolated VIBE_HOME so the agent process never reads or
 * writes the runner's real vibe state, and so the PR's own `.vibe/`
 * directory is never loaded: headless runs start untrusted and the project
 * layer stays empty without `--trust`.
 */
export interface VibeRunConfig {
  /** Pinned CLI version, e.g. "3.0.3". Resolved from the environment. */
  version: string;
  /** Model name, e.g. "mistral-large-latest". */
  model: string;
  /** Max assistant turns for the whole repair run. */
  maxTurns: number;
  /** Wall-clock budget for the run, in seconds. */
  timeLimitSeconds: number;
}

export const DEFAULT_VIBE_CONFIG: Omit<VibeRunConfig, 'version'> = {
  model: '',
  maxTurns: 40,
  timeLimitSeconds: 45 * 60,
};

/** The repair doctrine, loaded by vibe as the system prompt. */
export const REPAIR_SYSTEM_PROMPT_ID = 'dependency-repair';

/**
 * Renders the config.toml for one repair run.
 *
 * Hardening choices:
 * - `outside_workdir = "deny"`: file and shell tools may not leave the
 *   repair workspace (defense in depth on top of the patch validation).
 * - `system_prompt_id` points at the repair doctrine shipped by the
 *   framework ($VIBE_HOME/prompts/dependency-repair.md, written by the
 *   provider); the PR's own prompts never load.
 * - `[tools.bash] permission = "always"` with an explicit allowlist: the
 *   verification commands come from the trusted base-branch
 *   `.maintenance.yml`, and the agent needs to run them. Headless mode
 *   denies unanswerable approval prompts, so a non-allowlisted command
 *   fails closed instead of hanging.
 * - No MCP servers, no connectors, no hooks, no plugins.
 */
export function renderVibeConfig(request: RepairRequest, run: VibeRunConfig): string {
  const commands = [request.commands.install, request.commands.build, request.commands.test]
    .filter((c): c is string => Boolean(c))
    .map((c) => firstWord(c));
  const allowlist = [...new Set(['git', 'pnpm', 'npm', 'node', ...commands])];
  return [
    '# Generated by the framework repair provider; do not edit.',
    // An empty active_model resolves to the vibe default (currently
    // mistral-medium-3.5); REPAIR_MODEL_NAME pins an explicit alias.
    `active_model = "${run.model}"`,
    `system_prompt_id = "${REPAIR_SYSTEM_PROMPT_ID}"`,
    'outside_workdir = "deny"',
    'enable_telemetry = false',
    '',
    '[tools.bash]',
    'permission = "always"',
    `allowlist = ${JSON.stringify(allowlist)}`,
    `default_timeout = ${Math.ceil(run.timeLimitSeconds / 2)}`,
    `max_timeout_seconds = ${Math.ceil(run.timeLimitSeconds / 2)}`,
    '',
  ].join('\n');
}

/**
 * Writes config.toml and the repair doctrine prompt into the isolated vibe
 * home; returns the home path.
 */
export function writeVibeHome(vibeHome: string, configToml: string, systemPrompt: string): string {
  mkdirSync(join(vibeHome, 'prompts'), { recursive: true });
  writeFileSync(join(vibeHome, 'config.toml'), configToml);
  writeFileSync(join(vibeHome, 'prompts', `${REPAIR_SYSTEM_PROMPT_ID}.md`), systemPrompt);
  return vibeHome;
}

function firstWord(command: string): string {
  return command.trim().split(/\s+/)[0] ?? command;
}
